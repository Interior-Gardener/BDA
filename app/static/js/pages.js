function funnelChart(el, f) {
  if (!f) return;
  // sequential ramp: larger step = more intense (lighter on dark, darker on light)
  const dark = document.documentElement.dataset.theme === 'dark';
  const colors = dark ? ['#86b6ef', '#5598e7', '#2a78d6', '#1c5cab', '#184f95'] : ['#0d366b', '#184f95', '#256abf', '#3987e5', '#6da7ec'];
  const ink = (i) => (dark && i < 2 ? '#0b1020' : '#fff');
  return chart(el, {
    tooltip: { trigger: 'item', ...tooltipStyle(), formatter: (p) => `${p.name}<br><b>${fmt.num(p.data.sessions)}</b> sessions · ${p.data.pct}% of all` },
    series: [{
      type: 'funnel', left: 10, right: 10, top: 6, bottom: 6, minSize: '18%', gap: 3, sort: 'none',
      label: { position: 'inside', color: '#fff', fontWeight: 600, fontSize: 12, formatter: (p) => `${p.name}  ${p.data.pct}%` },
      itemStyle: { borderWidth: 0 },
      data: f.steps.map((s, i) => ({ name: s.step, value: 100 - i * 15, sessions: s.sessions, pct: s.pct_of_sessions, itemStyle: { color: colors[i] }, label: { color: ink(i) } })),
    }],
  });
}

